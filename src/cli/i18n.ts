export type Lang = "en" | "zh-CN";

export const CATALOGS: Record<Lang, Catalog> = { en, "zh-CN": zhCN };

/** Map any locale string to a supported language, or undefined. */
export function normalizeLang(value: string | undefined | null): Lang | undefined {
  const v = String(value ?? "")
    .trim()
    .toLowerCase();
  if (!v || v === "c" || v === "posix" || v === "auto") return undefined;
  if (v.startsWith("zh")) return "zh-CN";
  if (v.startsWith("en")) return "en";
  return undefined;
}

/**
 * Resolve the language.
 *
 * Order: explicit `--lang`, then OPENCODE_SYNC_LANG, then the menu setting,
 * then LC_ALL / LC_MESSAGES / LANG, then the runtime's Intl locale.
 */
export function detectLang(
  explicit?: string,
  setting?: string,
  env: NodeJS.ProcessEnv = process.env,
  intlLocale: () => string = () => Intl.DateTimeFormat().resolvedOptions().locale,
): Lang {
  const candidates = [
    explicit,
    env.OPENCODE_SYNC_LANG,
    setting,
    env.LC_ALL,
    env.LC_MESSAGES,
    env.LANG,
  ];
  for (const c of candidates) {
    const lang = normalizeLang(c);
    if (lang) return lang;
  }
  try {
    return normalizeLang(intlLocale()) ?? "en";
  } catch {
    return "en";
  }
}

let current: Lang = "en";

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export type Vars = Record<string, string | number>;

export function t(key: MessageKey, vars: Vars = {}, lang: Lang = current): string {
  const template = CATALOGS[lang][key] ?? CATALOGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Relative time in the current language. */
export function ago(timestamp: number | undefined, now = Date.now()): string {
  if (!timestamp) return t("never");
  const minutes = Math.round((now - timestamp) / 60000);
  if (minutes < 1) return t("justNow");
  if (minutes < 60) return t("minutesAgo", { n: minutes });
  const hours = Math.round(minutes / 60);
  if (hours < 48) return t("hoursAgo", { n: hours });
  return t("daysAgo", { n: Math.round(hours / 24) });
}
